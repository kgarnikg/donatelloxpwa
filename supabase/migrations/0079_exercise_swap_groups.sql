create or replace function public.swap_group_fallback(g text)
returns text
language sql
immutable
as $$
  -- Второй круг поиска, если в точной группе замены не нашлось
  -- (маленькие группы: шраги, пуловер, становая...). Всегда та же зона тела.
  select case g
    when 'rear_delts' then 'shoulders'
    when 'traps' then 'shoulders'
    when 'pullover' then 'back'
    when 'deadlift' then 'hamstrings'
    when 'lower_back' then 'hamstrings'
    when 'arms' then 'block_arms'
    when 'core' then 'block_core'
    when 'warmup' then 'block_warmup'
    when 'block_warmup' then 'warmup'
    when 'cardio' then 'block_cardio'
    when 'full_body' then 'block_full_body'
    when 'block_rear_delts' then 'block_shoulders'
    when 'block_deadlift' then 'block_legs'
    when 'block_glutes' then 'block_legs'
    when 'block_push' then 'block_chest'
    when 'block_pull' then 'block_back'
    else null
  end
$$;

create or replace function public.suggest_exercise_swaps(p_exercise_id uuid, p_workout_id uuid)
returns setof public.exercises
language sql
stable
security invoker
set search_path = public
as $$
  with src as (
    select swap_group,
           public.swap_group_fallback(swap_group) as fallback_group,
           lower(btrim(regexp_replace(title, '\s*[\(\+].*$', ''))) as base
    from public.exercises
    where id = p_exercise_id
  ),
  fmt as (
    select p.training_format
    from public.workouts w
    join public.workout_programs p on p.id = w.program_id
    where w.id = p_workout_id
  ),
  pool as (
    select distinct on (lower(btrim(regexp_replace(e.title, '\s*[\(\+].*$', ''))))
           e.*,
           case when e.swap_group = src.swap_group then 1 else 2 end as tier
    from public.exercises e, src
    where src.swap_group is not null
      and src.swap_group <> 'other'
      and (e.swap_group = src.swap_group or e.swap_group = src.fallback_group)
      and e.id <> p_exercise_id
      and lower(btrim(regexp_replace(e.title, '\s*[\(\+].*$', ''))) <> src.base
      and not exists (
        select 1 from public.workout_sets s
        where s.workout_id = p_workout_id and s.exercise_id = e.id
      )
      and exists (
        select 1
        from public.workout_sets s
        join public.workouts w on w.id = s.workout_id
        join public.workout_programs p on p.id = w.program_id
        where s.exercise_id = e.id
          and p.training_format = (select training_format from fmt)
      )
    order by lower(btrim(regexp_replace(e.title, '\s*[\(\+].*$', ''))),
             case when e.swap_group = src.swap_group then 1 else 2 end,
             (e.title ~ '[\(\+]'),
             length(e.title)
  ),
  best as (
    select * from pool where tier = (select min(tier) from pool)
  )
