-- 0079: группа замены упражнения ("Заменить" в тренировке).
--
-- Раньше замена искала похожее упражнение по первому слову названия:
-- "Жим гантелей" (грудь) находил "Жим ногами" — в день ГРУДЬ + ТРИЦЕПС
-- человеку подсовывали упражнение на ноги. muscle_groups почти у всех
-- упражнений пустое, опереться было не на что.
--
-- Теперь у каждого упражнения есть swap_group — на что его можно менять:
--   одиночные: chest, back, shoulders, biceps, triceps, quads, hamstrings,
--              glutes, calves, core, cardio, full_body, warmup, arms
--   блоки/круги/суперсеты: block_<группа> (block_chest, block_legs,
--              block_core, block_cardio, block_push, block_pull, block_upper,
--              block_arms, block_full_body, block_warmup ...)
--   other — заголовки-плейсхолдеры ("SHOULDERS — GIANT SET", "ПРОГРЕСС
--              МЕСЯЦА 4", контрольные тесты): менять нечего, кнопки нет.
-- Разметка сделана правилами по названию (RU/EN) и проверена выборочно;
-- поправить конкретное упражнение можно в SQL: update exercises set
-- swap_group = '...' where slug = '...'.
--
-- suggest_exercise_swaps() — кандидаты на замену: та же swap_group, тот же
-- формат (зал/дом) программы, без упражнений, которые уже есть в этой
-- тренировке, без дублей "то же упражнение с другой пометкой".

alter table public.exercises add column if not exists swap_group text;

comment on column public.exercises.swap_group is
  'На что можно заменить упражнение кнопкой "Заменить": chest/back/shoulders/biceps/triceps/quads/hamstrings/glutes/calves/core/cardio/full_body/warmup, block_<группа> для кругов и суперсетов, other — не менять.';

create index if not exists exercises_swap_group_idx on public.exercises (swap_group);
-- Поиск кандидатов проверяет, в каких программах (зал/дом) встречается упражнение.
create index if not exists workout_sets_exercise_id_idx on public.workout_sets (exercise_id);

