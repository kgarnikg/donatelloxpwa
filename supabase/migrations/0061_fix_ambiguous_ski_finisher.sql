-- 0061_fix_ambiguous_ski_finisher.sql
-- Исправление неоднозначной формулировки: "Кардио-финишер: 30 сек
-- высокий темп / 60 сек спокойно ×7" не указывало, на каком тренажёре —
-- дорожка или лыжи. Пользователь подтвердил: лыжи/SkiErg. Это единичное
-- вхождение — женская программа "Похудение (зал)", месяц/неделя 2,
-- день "FULL BODY + CONDITIONING" (см. PROJECT_PLAN.md).
--
-- Не знаем заранее, куда именно осел текст при исходной вставке —
-- отдельной записью в каталоге exercises.title или в заметке
-- workout_sets.notes к общему "Кардио" упражнению. Обновляем оба места
-- по точному совпадению текста — не найдётся в одном, просто не
-- затронет ни одной строки там, безопасно.
--
-- Безопасно выполнять повторно (после первого раза старого текста уже
-- не будет — WHERE ничего не найдёт).

update public.exercises
set title = 'Кардио-финишер: лыжи/SkiErg — 30 сек высокий темп / 60 сек спокойно ×7'
where title = 'Кардио-финишер: 30 сек высокий темп / 60 сек спокойно ×7';

update public.workout_sets
set notes = 'Кардио-финишер: лыжи/SkiErg — 30 сек высокий темп / 60 сек спокойно ×7'
where notes = 'Кардио-финишер: 30 сек высокий темп / 60 сек спокойно ×7';
